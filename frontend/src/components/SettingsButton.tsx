import { GearIcon } from './icons';

interface SettingsButtonProps {
  /** Открыть окно настроек модели */
  onOpen(): void;
}

/**
 * Единственный вход в выбор модели — тот самый значок, который лежал в
 * репозитории неиспользованным вместе со своим стилем.
 *
 * Подпись и `aria-label` одинаковы: рядом только значок, и без текста кнопка
 * для программ чтения с экрана осталась бы безымянной. Секрета здесь нет и быть
 * не может — кнопка ничего о профиле не знает.
 *
 * `.settings-fab` сама по себе висела с `opacity: 0` и показывалась только при
 * наведении: у функции не было заметного начала работы. Теперь у покоя своя
 * прозрачность, и на узких экранах кнопка уходит под значок модели, а не под
 * него заезжает (GAP-25).
 */
export function SettingsButton({ onOpen }: SettingsButtonProps) {
  return (
    <button
      type="button"
      className="settings-fab"
      onClick={onOpen}
      title="Настройки модели"
      aria-label="Настройки модели"
    >
      <GearIcon />
    </button>
  );
}

import { useMemo } from 'react';

import type { AiProvider } from '@recon/shared';

import type { AiRuntimeInfo } from '../api';

/** Провайдер словами оператора. Секрет сюда не попадает и попасть не может. */
export function providerLabel(provider: AiProvider): string {
  return provider === 'openrouter' ? 'OpenRouter' : 'Ollama (локально)';
}

/**
 * Сохранённый выбор в том виде, в каком его нужно для подписи в шапке: два поля,
 * а не весь профиль. `apiKey` намеренно не входит в форму — значку секрет не нужен,
 * и держать его в типах, которые читает `App`, значило бы раздавать его дальше.
 */
export interface ModelChoice {
  /** Идентификатор модели из профиля; пустая строка — профиля нет */
  model: string;
  /** Пара сохранена целиком, поэтому запросы поедут через удалённый шлюз */
  isRemote: boolean;
}

/** Что применяется прямо сейчас и откуда об этом известно */
export interface ActiveAiModel {
  /** Идентификатор модели; null — определить нечем, и врать не о чем */
  model: string | null;
  /** Откуда взялось имя. Текст для title, секрета не содержит */
  source: string;
}

/**
 * Подпись в шапке: модель задания важнее профиля, профиль важнее настроек сервера.
 *
 * Порядок отвечает на вопрос «что **реально** работает», а не «что настроено»:
 *
 *  1. `jobModel` — то, что уже обслужило запуск. Профиль, отредактированный
 *     посреди работы, не имеет права переименовать идущее задание: подпись была бы
 *     правдой в момент старта и ложью через минуту.
 *  2. `server === null` — backend не отвечает. Локальная модель из settings.txt
 *     осталась бы в подписи последней известной правдой, а правдой она тут не
 *     является, поэтому показываем отсутствие.
 *  3. Сохранённая пара целиком — уйдёт в шлюз именно она, и `/api/health` о ней
 *     не знает: маршрут общий для всех, кто зашёл на этот backend.
 *  4. Настройки сервера — единственный случай, где «локальная модель» истинна.
 *
 * Путь 1 не срабатывает, пока модель не ответила: `effectiveModel` приходит
 * `null` — и это молчание верно, потому что подписать задание именем выбранной
 * модели значило бы сказать, что она работала. Разницы между локальным и
 * удалённым запуском тут нет: локальная модель тоже отвечает своим именем, и
 * путь 1 работает для обоих.
 */
export function useAiModelBadge(
  choice: ModelChoice,
  jobModel: string | null,
  server: AiRuntimeInfo | null,
): ActiveAiModel {
  const { isRemote, model } = choice;

  return useMemo<ActiveAiModel>(() => {
    if (jobModel !== null) {
      return { model: jobModel, source: 'Модель, которая ответила на текущий запуск.' };
    }
    if (server === null) {
      return { model: null, source: 'Backend недоступен — какая модель ответит, неизвестно.' };
    }
    if (isRemote) {
      // «Запрошено», а не «обработало»: ни один вызов удалённого шлюза ещё не
      // состоялся. Здесь важно не дать подписи обещать обработку — тем более
      // что локальной замены при отказе шлюза не происходит вовсе.
      return { model, source: 'Запрошено для следующего запуска: профиль OpenRouter, сохранённый в этом браузере.' };
    }
    return { model: server.model, source: 'Локальная модель из settings.txt.' };
  }, [isRemote, model, jobModel, server]);
}
